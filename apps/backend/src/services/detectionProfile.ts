import { createHash } from "crypto";
import { AppError } from "../middleware/error.middleware";

/**
 * Per-attack-type response rules, kept pure so they can be tested without a database.
 *
 * DOS_DDOS detections come from the offline/network sensor and are ALERT-ONLY:
 * they never move an endpoint to AT_RISK, never join ransomware cascade
 * correlation, never isolate an endpoint, only match policies that explicitly
 * target DOS_DDOS, and get no CTI draft until DoS-specific templates exist.
 * Ransomware, privilege-escalation and data-exfiltration behaviour is unchanged.
 */

export const ATTACK_TYPES = ["RANSOMWARE", "PRIVILEGE_ESCALATION", "DATA_EXFILTRATION", "DOS_DDOS"] as const;
export type AttackTypeValue = (typeof ATTACK_TYPES)[number];

/**
 * LIVE: real telemetry. PCAP_REPLAY: a recorded capture processed offline.
 * SIMULATED: synthetic telemetry (agent simulator). DEMO: seeded demonstration records.
 */
export const DATA_ORIGINS = ["LIVE", "PCAP_REPLAY", "SIMULATED", "DEMO"] as const;

/** Prefix stamped on CTI built from demo data. It is part of the hashed report content. */
export const DEMO_CTI_LABEL =
  "DEMONSTRATION RECORD - NOT THREAT INTELLIGENCE. Generated by SentinelIQ from seeded demonstration data; " +
  "it does not describe a real incident. ";

/**
 * Seeded demonstration data, never a real incident: dataOrigin DEMO, or records from the demo
 * seed script that predate the field (rule ids DEMO-..., model versions DEMO-...).
 */
export function isDemoDetection(d: { dataOrigin?: string | null; ruleId?: string | null; modelVersion?: string | null }): boolean {
  return d.dataOrigin === "DEMO" || /^DEMO-/i.test(d.ruleId ?? "") || /^DEMO-/i.test(d.modelVersion ?? "");
}
export type DataOrigin = (typeof DATA_ORIGINS)[number];

/**
 * Test records: seeded demonstration data or synthetic (simulated) telemetry. They are real rows,
 * never deleted or rewritten, but they are not security incidents, so ordinary views leave them
 * out and only an explicit request for test records returns them.
 */
export function isTestRecord(d: { dataOrigin?: string | null; ruleId?: string | null; modelVersion?: string | null }): boolean {
  return isDemoDetection(d) || d.dataOrigin === "SIMULATED";
}

/** The same rule as isTestRecord, as a MongoDB filter. */
export const TEST_RECORD_FILTER = {
  $or: [
    { dataOrigin: { $in: ["DEMO", "SIMULATED"] } },
    { ruleId: { $regex: /^DEMO-/i } },
    { modelVersion: { $regex: /^DEMO-/i } },
  ],
};

/** Prefix for CTI built from simulated telemetry; same recognisable start as DEMO_CTI_LABEL. */
export const SIMULATED_CTI_LABEL =
  "DEMONSTRATION RECORD - NOT THREAT INTELLIGENCE. Generated by SentinelIQ from simulated endpoint telemetry; " +
  "it does not describe a real incident. ";

/** CTI reports built from test records: a [DEMO] title, the labelled summary, or a DEMO- detector. */
export const TEST_REPORT_FILTER = {
  $or: [
    { title: { $regex: /^\[DEMO\]/ } },
    { attackSummary: { $regex: /^DEMONSTRATION RECORD/ } },
    { "detector.id": { $regex: /^DEMO-/i } },
  ],
};

export function reportScopeFilter(scope: RecordScope): Record<string, unknown> {
  if (scope === "test") return TEST_REPORT_FILTER;
  if (scope === "incidents") return { $nor: [TEST_REPORT_FILTER] };
  return {};
}

/** Which records a listing covers: incidents only (default), test records only, or both. */
export type RecordScope = "incidents" | "test" | "all";

export function parseRecordScope(value: unknown): RecordScope {
  if (value === undefined || value === "") return "incidents";
  if (value === "incidents" || value === "test" || value === "all") return value;
  throw new AppError('scope must be "incidents", "test" or "all"', 400);
}

export function scopeFilter(scope: RecordScope): Record<string, unknown> {
  if (scope === "test") return TEST_RECORD_FILTER;
  if (scope === "incidents") return { $nor: [TEST_RECORD_FILTER] };
  return {};
}

/**
 * Identity of a sensor alert episode, so replaying the same recorded alert never creates a second
 * detection. Only payloads that carry their own time and rule (sensor alerts) get one; agent
 * detections stamped with the server time keep their existing behaviour.
 */
export function sourceAlertKey(p: {
  endpointId: string; attackType?: string; ruleId?: string; modelVersion?: string; detectedAt?: Date; dataOrigin?: string;
  evidence?: Array<{ fields?: Record<string, unknown> }>;
}): string | undefined {
  if (!p.ruleId || !p.detectedAt || Number.isNaN(p.detectedAt.getTime())) return undefined;
  const target = String(p.evidence?.find((e) => e?.fields?.target !== undefined)?.fields?.target ?? "");
  const material = [p.endpointId, p.dataOrigin ?? "", p.attackType ?? "", p.ruleId, p.modelVersion ?? "", p.detectedAt.toISOString(), target].join("|");
  return createHash("sha256").update(material).digest("hex");
}

/** What produced a DoS detection. SYNTHETIC_TEST_ONLY models are refused at ingest. */
export const DETECTOR_STATUSES = ["TRAINED", "HEURISTIC"] as const;
export type DetectorStatus = (typeof DETECTOR_STATUSES)[number];

const CONFIDENCE_TIERS = ["suspicious", "likely", "confirmed"];

export interface ResponseProfile {
  markEndpointAtRisk: boolean;
  runCascadeCorrelation: boolean;
  runPolicies: boolean;
  allowIsolation: boolean;
  /** When true, a policy only applies if it has an explicit detectionType condition for this type. */
  requireExplicitPolicyMatch: boolean;
  ctiDraftSupported: boolean;
  threatLabel: string;
  atRiskReason: string;
}

const PROFILES: Record<AttackTypeValue, ResponseProfile> = {
  RANSOMWARE: {
    markEndpointAtRisk: true, runCascadeCorrelation: true, runPolicies: true, allowIsolation: true,
    requireExplicitPolicyMatch: false, ctiDraftSupported: true,
    threatLabel: "Threat", atRiskReason: "Active ransomware threat detected",
  },
  PRIVILEGE_ESCALATION: {
    markEndpointAtRisk: true, runCascadeCorrelation: false, runPolicies: false, allowIsolation: false,
    requireExplicitPolicyMatch: false, ctiDraftSupported: true,
    threatLabel: "Privilege escalation", atRiskReason: "Active privilege escalation detected",
  },
  DATA_EXFILTRATION: {
    markEndpointAtRisk: true, runCascadeCorrelation: true, runPolicies: true, allowIsolation: true,
    requireExplicitPolicyMatch: false, ctiDraftSupported: true,
    threatLabel: "Threat", atRiskReason: "Active ransomware threat detected",
  },
  DOS_DDOS: {
    markEndpointAtRisk: false, runCascadeCorrelation: false, runPolicies: true, allowIsolation: false,
    requireExplicitPolicyMatch: true, ctiDraftSupported: false,
    threatLabel: "DoS/DDoS", atRiskReason: "",
  },
};

// Other producers and seeded records use further types (LATERAL_MOVEMENT, ...);
// ingest has always accepted them, so any well-formed identifier still is.
const ATTACK_TYPE_PATTERN = /^[A-Z][A-Z0-9_]{1,63}$/;

/** Returns the attack type to store. Missing -> RANSOMWARE (historical default); malformed -> 400. */
export function normalizeAttackType(value: unknown): string {
  if (value === undefined || value === null || value === "") return "RANSOMWARE";
  if (typeof value === "string" && ATTACK_TYPE_PATTERN.test(value)) return value;
  throw new AppError("attackType must be an upper-case identifier such as RANSOMWARE or DOS_DDOS", 400);
}

/**
 * Types without their own profile keep the behaviour every detection had before
 * per-type profiles existed (the ransomware path), so nothing existing changes.
 */
export function responseProfile(attackType: string | undefined): ResponseProfile {
  const type = normalizeAttackType(attackType);
  return PROFILES[type as AttackTypeValue] ?? PROFILES.RANSOMWARE;
}

export interface IngestDoSFields {
  dataOrigin?: DataOrigin;
  detectorStatus?: DetectorStatus;
}

/**
 * Validates the attack-type-specific ingest fields. A DOS_DDOS detection must say
 * where its data came from and what produced it, and may not claim "confirmed".
 */
export function validateIngestFields(body: {
  attackType?: unknown;
  confidenceTier?: unknown;
  dataOrigin?: unknown;
  detectorStatus?: unknown;
}): { attackType: string } & IngestDoSFields {
  const attackType = normalizeAttackType(body.attackType);
  if (body.confidenceTier !== undefined && !CONFIDENCE_TIERS.includes(String(body.confidenceTier))) {
    throw new AppError(`confidenceTier must be one of ${CONFIDENCE_TIERS.join(", ")}`, 400);
  }
  if (body.dataOrigin !== undefined && !(DATA_ORIGINS as readonly unknown[]).includes(body.dataOrigin)) {
    throw new AppError(`dataOrigin must be one of ${DATA_ORIGINS.join(", ")}`, 400);
  }
  if (attackType !== "DOS_DDOS") {
    return { attackType, dataOrigin: body.dataOrigin as DataOrigin | undefined };
  }
  if (body.dataOrigin === undefined) {
    throw new AppError("DOS_DDOS detections must state dataOrigin (LIVE, PCAP_REPLAY, SIMULATED or DEMO)", 400);
  }
  if (!(DETECTOR_STATUSES as readonly unknown[]).includes(body.detectorStatus)) {
    throw new AppError(`DOS_DDOS detections need detectorStatus ${DETECTOR_STATUSES.join(" or ")}; ` +
      "synthetic or untrained detectors are not accepted", 400);
  }
  if (body.confidenceTier === "confirmed") {
    throw new AppError("DOS_DDOS detections may not claim confidenceTier 'confirmed'", 400);
  }
  return {
    attackType,
    dataOrigin: body.dataOrigin as DataOrigin,
    detectorStatus: body.detectorStatus as DetectorStatus,
  };
}

interface PolicyLike {
  conditions: Array<{ field: string; operator?: string; value: unknown }>;
}

/**
 * Whether a policy may run for a detection type. For types that require an explicit
 * match (DOS_DDOS), a ransomware-oriented rule such as "riskScore >= 80 -> isolate"
 * never applies; only a policy with a detectionType condition naming the type does.
 */
export function policyAppliesToDetection(policy: PolicyLike, detectionType: string | undefined): boolean {
  const profile = responseProfile(detectionType);
  if (!profile.runPolicies) return false;
  if (!profile.requireExplicitPolicyMatch) return true;
  const type = normalizeAttackType(detectionType);
  return policy.conditions.some((c) => c.field === "detectionType" && c.operator === "EQUALS" && c.value === type);
}

/** Hard guard on automated actions, independent of how a policy is written. */
export function isActionAllowed(actionType: string, detectionType: string | undefined): boolean {
  if (actionType === "ISOLATE_ENDPOINT") return responseProfile(detectionType).allowIsolation;
  return true;
}

export function assertCtiDraftSupported(attackType: string | undefined): void {
  const type = normalizeAttackType(attackType);
  if (!responseProfile(type).ctiDraftSupported) {
    throw new AppError(`CTI drafts are not supported for ${type} detections yet (no attack-specific template)`, 422);
  }
}
