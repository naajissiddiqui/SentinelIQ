"""
Bounded offline demo: existing PCAP extraction -> heuristic DoS alert -> ingest payload files.

    ..\\apps\\ml-service\\.venv\\Scripts\\python.exe -B demo\\offline_demo.py \
        --extraction C:/datasets/netsensor-smoke/run1 --out-dir C:/datasets/dos-demo/run1

Nothing is sent anywhere and no traffic is generated. The detector is the
transparent packets-per-second HEURISTIC (netsensor/ml/model.py), not a trained
model: no supervised model exists yet because the label rules are unverified
and the labelled data fails the training gates. Every payload says so
(detectorStatus HEURISTIC, dataOrigin PCAP_REPLAY).

With --export-fixtures, the first alert payload is also written as a test fixture
for the backend and web tests (marked as a fixture inside the file).
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from netsensor.ml import STATUS_NOT_TRAINED  # noqa: E402
from netsensor.ml.cli import _score_extraction  # noqa: E402
from netsensor.ml.model import PpsHeuristic  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
FIXTURES = {
    "backend": os.path.join(REPO, "apps", "backend", "src", "tests", "fixtures", "dos-pcap-replay-alert.fixture.json"),
    "web": os.path.join(REPO, "apps", "web", "src", "lib", "fixtures", "dos-pcap-replay-alert.fixture.json"),
}
DEMO_ORG = "64b7f0000000000000000001"
DEMO_ENDPOINT = "64b7f0000000000000000002"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--extraction", required=True, help="existing extraction directory (windows.csv, stats.json)")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--threshold-pps", type=float, default=5000.0)
    ap.add_argument("--k", type=int, default=3)
    ap.add_argument("--n", type=int, default=3)
    ap.add_argument("--export-fixtures", action="store_true")
    args = ap.parse_args(argv)

    detector = PpsHeuristic(args.threshold_pps, args.k, args.n)
    run = _score_extraction(detector, args.extraction, args.out_dir, DEMO_ORG, DEMO_ENDPOINT, "PCAP_REPLAY")
    with open(os.path.join(args.out_dir, "alerts.jsonl"), encoding="utf-8") as stream:
        alerts = [json.loads(line) for line in stream]
    # The busiest window of a destination that never alerted shows how the
    # heuristic treats legitimate bursts.
    targets = {a["evidence"][0]["fields"]["target"] for a in alerts}
    busiest_quiet = None
    import csv
    with open(os.path.join(args.out_dir, "scores.csv"), newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            if row["dst_ip"] not in targets and (busiest_quiet is None or float(row["score"]) > float(busiest_quiet["score"])):
                busiest_quiet = row
    summary = {
        "detector": "pps-heuristic", "detector_status": run["status"],
        "supervised_model_status": STATUS_NOT_TRAINED,
        "why_no_model": "label rules unverified; labelled data fails the training gates (see training_refused.json)",
        "threshold_pps": args.threshold_pps, "persistence": detector.persistence,
        "data_origin": "PCAP_REPLAY", "extraction": run["extraction"], "captures": run["captures"],
        "windows_scored": run["counts"]["windows"], "alert_windows": run["counts"]["alert_windows"],
        "alerts": len(alerts),  # one per alert episode
        "first_alert": {k: alerts[0][k] for k in ("detectedAt", "riskScore", "confidenceTier", "ruleId")} if alerts else None,
        "alert_targets": sorted(targets),
        "busiest_window_of_a_non_alerting_destination": busiest_quiet,
    }
    with open(os.path.join(args.out_dir, "demo_summary.json"), "w", encoding="utf-8", newline="\n") as stream:
        json.dump(summary, stream, indent=2, sort_keys=True)
        stream.write("\n")
    print(json.dumps(summary, indent=2))

    if args.export_fixtures:
        if not alerts:
            print("no alert to export", file=sys.stderr)
            return 1
        fixture = dict(alerts[0])
        fixture["_fixture"] = ("TEST FIXTURE generated by sensor/demo/offline_demo.py from an offline PCAP "
                               "extraction (PCAP replay, pps HEURISTIC, not a trained model).")
        for name, path in FIXTURES.items():
            if os.path.exists(path):
                print(f"{name} fixture exists, not overwriting: {path}", file=sys.stderr)
                continue
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as stream:
                json.dump(fixture, stream, indent=2, sort_keys=True)
                stream.write("\n")
            print(f"wrote {name} fixture: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
